/* Builds src/data/dot-world.ts — the dotted world map on the passport's record page.
 *
 *   node scripts/build-dot-world.mjs path/to/worldLow.json
 *
 * Input: amCharts' worldLow.json (https://cdn.amcharts.com/lib/5/geodata/json/worldLow.json), the same
 * country shapes the Atlas draws. Output: a COLS × ROWS equirectangular grid; every land cell remembers
 * the country it belongs to, so the page can light up the countries the traveller has been to. A country
 * too small to own a cell (Belgium, Singapore …) is lit by the land cell nearest to its centre instead.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const COLS = 96;
const LAT_TOP = 84;
const LAT_BOTTOM = -57;                       // no Antarctica
const STEP = 360 / COLS;
const ROWS = Math.round((LAT_TOP - LAT_BOTTOM) / STEP);

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-dot-world.mjs worldLow.json'); process.exit(1); }
const geo = JSON.parse(readFileSync(src, 'utf8'));

/** Polygons of a feature as [outer, ...holes] ring lists, with a bounding box each. */
const shapes = [];
for (const f of geo.features) {
  const iso = f.properties?.id;
  if (!iso || iso === 'AQ') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const rings of polys) {
    let x0 = 999, x1 = -999, y0 = 999, y1 = -999;
    for (const [x, y] of rings[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
    shapes.push({ iso, rings, x0, x1, y0, y1 });
  }
}

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const isoAt = (x, y) => {
  for (const s of shapes) {
    if (x < s.x0 || x > s.x1 || y < s.y0 || y > s.y1) continue;
    if (!inRing(x, y, s.rings[0])) continue;
    if (s.rings.slice(1).some((h) => inRing(x, y, h))) continue;
    return s.iso;
  }
  return '';
};

const isos = [];
const idx = (iso) => { let i = isos.indexOf(iso); if (i < 0) { isos.push(iso); i = isos.length - 1; } return i; };
const code = (n) => n.toString(36).padStart(2, '0');

const rows = [];
for (let r = 0; r < ROWS; r++) {
  let line = '';
  const lat = LAT_TOP - (r + 0.5) * STEP;
  for (let c = 0; c < COLS; c++) {
    const lng = -180 + (c + 0.5) * STEP;
    // The centre first, then four points around it, so a thin country or a narrow strait still shows.
    let hit = isoAt(lng, lat);
    if (!hit) for (const [dx, dy] of [[-.3, -.3], [.3, -.3], [-.3, .3], [.3, .3]]) { hit = isoAt(lng + dx * STEP, lat + dy * STEP); if (hit) break; }
    line += hit ? code(idx(hit) + 1) : '..';   // 00 is "sea" in the encoding, so index + 1
  }
  rows.push(line);
}

/** Centre of each country's biggest piece, for the ones with no cell of their own. */
const centres = {};
const biggest = {};
for (const s of shapes) {
  const area = (s.x1 - s.x0) * (s.y1 - s.y0);
  if (!biggest[s.iso] || area > biggest[s.iso]) { biggest[s.iso] = area; centres[s.iso] = [Math.round((s.y0 + s.y1) / 2 * 10) / 10, Math.round((s.x0 + s.x1) / 2 * 10) / 10]; }
}
const owned = new Set(isos);
const lone = Object.fromEntries(Object.entries(centres).filter(([iso]) => !owned.has(iso)));

const out = `/* GENERATED by scripts/build-dot-world.mjs from amCharts worldLow.json — do not edit. */

/** Grid of the dotted world: ${COLS} × ${ROWS} cells, equirectangular, ${LAT_TOP}°N → ${Math.abs(LAT_BOTTOM)}°S. */
export const DOT_COLS = ${COLS};
export const DOT_ROWS = ${ROWS};
export const DOT_LAT_TOP = ${LAT_TOP};
export const DOT_STEP = ${STEP};

/** Countries that own at least one cell; a cell's code is (index + 1) in base 36, two digits, '..' = sea. */
export const DOT_ISOS: readonly string[] = ${JSON.stringify(isos)};

/** One string per row, ${COLS} two-character cells. */
export const DOT_ROWS_DATA: readonly string[] = ${JSON.stringify(rows, null, 0).replace(/","/g, '",\n  "')};

/** [lat, lng] of countries too small for a cell of their own — lit by the nearest land cell. */
export const DOT_LONE: Readonly<Record<string, readonly [number, number]>> = ${JSON.stringify(lone)};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '../src/data/dot-world.ts'), out);
console.log(`dot-world.ts: ${COLS}×${ROWS}, ${isos.length} countries own cells, ${Object.keys(lone).length} lit by centre`);
