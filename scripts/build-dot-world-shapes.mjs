/* Builds src/data/dot-world-shapes.ts — country outlines for the passport map's magnifier.
 *
 *   node scripts/build-dot-world-shapes.mjs path/to/worldLow.json
 *
 * Same input and the same grid as build-dot-world.mjs (https://cdn.amcharts.com/lib/5/geodata/json/worldLow.json),
 * so an outline lands exactly on the dots it belongs to. Each country becomes one SVG path in grid units
 * (1 unit = one dot cell), thinned with Douglas–Peucker: enough to read a coastline at 5× zoom, small enough
 * to load only when the magnifier is first used.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const COLS = 96;
const LAT_TOP = 84;
const STEP = 360 / COLS;
const TOLERANCE = 0.22;        // degrees
const MIN_SPAN = 0.35;         // rings narrower than this in both directions are dropped (unless they are all a country has)

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-dot-world-shapes.mjs worldLow.json'); process.exit(1); }
const geo = JSON.parse(readFileSync(src, 'utf8'));

function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    let far = -1, dmax = 0;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len;
      if (d > dmax) { dmax = d; far = i; }
    }
    if (far > 0 && dmax > tol) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const span = (ring) => {
  let x0 = 999, x1 = -999, y0 = 999, y1 = -999;
  for (const [x, y] of ring) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return Math.max(x1 - x0, y1 - y0);
};
const gx = (lng) => ((lng + 180) / STEP);
const gy = (lat) => ((LAT_TOP - lat) / STEP);
const num = (n) => String(Math.round(n * 100) / 100);

const shapes = {};
for (const f of geo.features) {
  const iso = f.properties?.id;
  if (!iso || iso === 'AQ' || !/^[A-Z]{2}$/.test(iso)) continue;      // sub-national codes (UM-DQ …) have no place in a country list
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.map((p) => p[0]);                // outer rings only: holes (lakes, enclaves) are not worth the bytes
  const big = rings.filter((r) => span(r) >= MIN_SPAN);
  const use = big.length ? big : [rings.sort((a, b) => span(b) - span(a))[0]];
  const d = use.map((r) => {
    // A ring starts and ends on the same point, which Douglas–Peucker cannot measure from: split it at the point farthest from the start.
    let m = 1;
    for (let i = 1; i < r.length; i++) if (Math.hypot(r[i][0] - r[0][0], r[i][1] - r[0][1]) > Math.hypot(r[m][0] - r[0][0], r[m][1] - r[0][1])) m = i;
    const pts = [...simplify(r.slice(0, m + 1), TOLERANCE), ...simplify(r.slice(m), TOLERANCE).slice(1, -1)];
    if (pts.length < 3) return '';
    return `M${pts.map(([x, y]) => `${num(gx(x))} ${num(gy(y))}`).join('L')}Z`;
  }).join('');
  if (d) shapes[iso] = (shapes[iso] ?? '') + d;
}

const body = Object.entries(shapes).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
const out = `/* GENERATED by scripts/build-dot-world-shapes.mjs from amCharts worldLow.json — do not edit. */

/** Country outlines (ISO alpha-2 → SVG path) in the dotted world's own grid units: 1 unit = one dot cell. */
export const DOT_SHAPES: Readonly<Record<string, string>> = {
${body}
};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '../src/data/dot-world-shapes.ts'), out);
console.log(`dot-world-shapes.ts: ${Object.keys(shapes).length} countries, ${(out.length / 1024).toFixed(0)} KB`);
